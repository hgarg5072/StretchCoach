    compose = true
    buildConfig = true
  }
  androidResources {
    noCompress += listOf("mp4", "m4a")
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
}

